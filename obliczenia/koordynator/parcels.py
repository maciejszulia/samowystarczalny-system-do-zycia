def area(pts):
    s=0
    for i in range(len(pts)):
        x1,y1=pts[i]; x2,y2=pts[(i+1)%len(pts)]
        s+=x1*y2-x2*y1
    return abs(s)/2
def perim(pts):
    return sum(math.dist(pts[i],pts[(i+1)%len(pts)]) for i in range(len(pts)))
